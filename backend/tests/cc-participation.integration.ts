import assert from 'node:assert/strict';
import fs from 'node:fs';
import sharp from 'sharp';
import { createApiApp } from '../app';
import { db, initializeDatabase } from '../db';
import { env } from '../env';
import { initializeCcParticipation, ccPhotoPath } from '../cc-participation-service';

assert.ok(env.databasePath.includes('test-runs'), 'Only use the isolated test DB.');
await initializeDatabase();
const server = createApiApp().listen(0, '127.0.0.1');
await new Promise<void>((resolve) => server.once('listening', resolve));
const address = server.address();
if (!address || typeof address === 'string') throw new Error('Missing test server');
const base = `http://127.0.0.1:${address.port}/api`;
const call = async (endpoint: string, method = 'GET', body?: unknown, cookie = '') => {
  const response = await fetch(base + endpoint, { method, headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
  return { status: response.status, payload: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] || '' };
};
try {
  const admin = (await call('/auth/login', 'POST', { username: 'user-5', password: '1234' })).cookie;
  const reader = (await call('/auth/login', 'POST', { username: 'user-1', password: '1234' })).cookie;
  assert.ok(admin && reader);
  // Simulate the prior schema to verify an additive upgrade preserves existing text.
  db.exec('ALTER TABLE cc_participation_document DROP COLUMN introduction_color');
  db.prepare('UPDATE cc_participation_document SET introduction = ?, bottom_text = ? WHERE id = 1').run('기존 상단 문구', '기존 하단 문구');
  initializeCcParticipation();
  assert.equal((await call('/cc-participation')).status, 401);
  let doc = (await call('/cc-participation', 'GET', undefined, admin)).payload.data;
  assert.equal(doc.canManage, true); assert.deepEqual(doc.sections, []);
  assert.equal(doc.introductionColor, '#475569');
  assert.equal(doc.introduction, '기존 상단 문구'); assert.equal(doc.bottomText, '기존 하단 문구');
  assert.equal((await call('/cc-participation', 'GET', undefined, reader)).payload.data.canManage, false);
  const input = { version: doc.version, introduction: '등록 안내', introductionColor: '#DC2626', bottomText: '하단 안내\n<script>window.__ccXss = true</script>', sections: [{ title: '글만 있는 항목', description: '사진 없이 설명만\n두 번째 줄', photoId: null }] };
  assert.equal((await call('/cc-participation', 'PUT', input, reader)).status, 403);
  assert.equal((await call('/cc-participation', 'PUT', { ...input, sections: new Array(6).fill(input.sections[0]) }, admin)).status, 400);
  assert.equal((await call('/cc-participation', 'PUT', { ...input, bottomText: 'a'.repeat(20001) }, admin)).status, 400);
  assert.equal((await call('/cc-participation', 'PUT', { ...input, introductionColor: 'red; background: url(test)' }, admin)).status, 400);
  const saved = await call('/cc-participation', 'PUT', input, admin);
  assert.equal(saved.status, 200); doc = saved.payload.data;
  assert.equal(doc.sections[0].photo, null); assert.equal(doc.bottomText, input.bottomText);
  assert.equal(doc.introductionColor, '#dc2626');
  assert.equal((await call('/cc-participation', 'PUT', input, admin)).status, 409);
  initializeCcParticipation(); initializeCcParticipation();
  assert.equal((await call('/cc-participation', 'GET', undefined, reader)).payload.data.bottomText, input.bottomText);
  assert.equal((await call('/cc-participation', 'GET', undefined, reader)).payload.data.introductionColor, '#dc2626');
  const photo = await sharp({ create: { width: 300, height: 150, channels: 3, background: '#2878b5' } }).jpeg().toBuffer();
  const upload = async (body: Buffer, cookie = admin, mime = 'image/jpeg') => {
    const response = await fetch(base + '/cc-participation/photos', { method: 'POST', headers: { Cookie: cookie, 'Content-Type': mime }, body: body as unknown as BodyInit });
    return { status: response.status, payload: await response.json() };
  };
  assert.equal((await upload(photo, reader)).status, 403);
  assert.equal((await upload(Buffer.from('fake JPEG'))).status, 400);
  assert.equal((await upload(photo, admin, 'image/png')).status, 400);
  const uploaded = await upload(photo); assert.equal(uploaded.status, 201);
  const id = uploaded.payload.data.id;
  assert.equal((await fetch(base + `/cc-participation/photos/${id}`)).status, 401);
  assert.equal((await fetch(base + `/cc-participation/photos/${id}`, { headers: { Cookie: reader } })).status, 404);
  const withPhoto = await call('/cc-participation', 'PUT', { version: doc.version, introduction: doc.introduction, bottomText: doc.bottomText, sections: [{ title: '사진과 설명', description: '등록된 사진 설명', photoId: id }] }, admin);
  assert.equal(withPhoto.status, 200); doc = withPhoto.payload.data;
  assert.equal(doc.introductionColor, '#dc2626', 'Older clients omitting the color must preserve it.');
  const content = await fetch(base + `/cc-participation/photos/${id}`, { headers: { Cookie: reader } });
  assert.equal(content.status, 200); assert.equal(content.headers.get('content-type'), 'image/webp');
  const metadata = await sharp(Buffer.from(await content.arrayBuffer())).metadata(); assert.equal(metadata.width, 300); assert.equal(metadata.height, 150);
  assert.equal((await call(`/cc-participation/photos/${id}`, 'DELETE', undefined, admin)).status, 409);
  const replacement = (await upload(photo)).payload.data.id;
  const replaced = await call('/cc-participation', 'PUT', { version: doc.version, bottomText: '사진 교체 후 하단 글', sections: [{ title: '교체 사진', description: '수정 설명', photoId: replacement }] }, admin);
  assert.equal(replaced.status, 200); doc = replaced.payload.data;
  assert.equal((await fetch(base + `/cc-participation/photos/${id}`, { headers: { Cookie: reader } })).status, 404);
  const oldPhoto = db.prepare('SELECT object_key, purged_at FROM cc_participation_photos WHERE id = ?').get(id) as { object_key: string; purged_at: string };
  assert.ok(oldPhoto.purged_at); assert.equal(fs.existsSync(ccPhotoPath(oldPhoto.object_key)), false);
  const onlyText = await call('/cc-participation', 'PUT', { version: doc.version, sections: [], bottomText: '사진 없이 맨 아래 글만 저장\n줄바꿈 유지' }, admin);
  assert.equal(onlyText.status, 200); assert.deepEqual(onlyText.payload.data.sections, []);
  assert.equal((await fetch(base + `/cc-participation/photos/${replacement}`, { headers: { Cookie: reader } })).status, 404);
  assert.equal((await call('/cc-participation', 'GET', undefined, reader)).payload.data.bottomText, onlyText.payload.data.bottomText);
  const unused = (await upload(photo)).payload.data.id;
  assert.equal((await call(`/cc-participation/photos/${unused}`, 'DELETE', undefined, reader)).status, 403);
  assert.equal((await call(`/cc-participation/photos/${unused}`, 'DELETE', undefined, admin)).status, 200);
  console.log('CC participation integration passed: persisted text-only/photo content, admin-only mutations, authenticated photos, validation, conflicts, idempotent migration, replacement/deletion cleanup.');
} finally { await new Promise<void>((resolve) => server.close(() => resolve())); db.close(); }
